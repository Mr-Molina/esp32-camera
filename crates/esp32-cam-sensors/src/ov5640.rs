/// Autofocus status decoded from `OV5640_CMD_FW_STATUS` (`0x3029`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Ov5640AfStatus {
    /// Raw status byte read from `0x3029`.
    pub raw: u8,
    /// True when `raw == OV5640_FW_STATUS_FOCUSED` (`0x10`).
    pub focused: bool,
    /// True when neither idle (`0x70`) nor focused (`0x10`).
    pub busy: bool,
}

/// OV5640 autofocus controller (`ov5640_af.c`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Ov5640Af {
    slv_addr: u8,
}

impl Default for Ov5640Af {
    fn default() -> Self {
        Self::new(CameraSccbAddr::OV5640)
    }
}

impl Ov5640Af {
    /// Creates a new [`Ov5640Af`] controller for `slv_addr`.
    pub const fn new(slv_addr: u8) -> Self {
        Self { slv_addr }
    }

    /// Returns true (`ov5640_af_is_supported`).
    pub const fn is_supported(&self) -> bool {
        true
    }

    /// Waits for `OV5640_CMD_ACK` (`0x3023`) to become `0x00` within `timeout_ms`.
    pub fn wait_ack_clear<B: SccbBus>(
        &self,
        bus: &mut B,
        timeout_ms: u32,
    ) -> Result<(), CameraError> {
        let mut elapsed_ms = 0u32;
        loop {
            let ack = bus.read_reg16(self.slv_addr, OV5640_CMD_ACK)?;
            if ack == 0x00 {
                return Ok(());
            }
            if elapsed_ms >= timeout_ms {
                return Err(CameraError::Timeout);
            }
            bus.delay_ms(5);
            elapsed_ms = elapsed_ms.saturating_add(5);
        }
    }

    /// Waits for `OV5640_CMD_FW_STATUS` (`0x3029`) to become `OV5640_FW_STATUS_IDLE` (`0x70`).
    pub fn wait_fw_idle<B: SccbBus>(
        &self,
        bus: &mut B,
        timeout_ms: u32,
    ) -> Result<(), CameraError> {
        let mut elapsed_ms = 0u32;
        loop {
            let st = bus.read_reg16(self.slv_addr, OV5640_CMD_FW_STATUS)?;
            if st == OV5640_FW_STATUS_IDLE {
                return Ok(());
            }
            if elapsed_ms >= timeout_ms {
                return Err(CameraError::Timeout);
            }
            bus.delay_ms(5);
            elapsed_ms = elapsed_ms.saturating_add(5);
        }
    }

    /// Loads `OV5640_AF_FIRMWARE` into MCU SRAM at `0x8000` and waits for `OV5640_FW_STATUS_IDLE` (`ov5640_af_init`).
    pub fn init<B: SccbBus>(&self, bus: &mut B, timeout_ms: u32) -> Result<(), CameraError> {
        bus.write_reg16(self.slv_addr, 0x3000, 0x20)?;
        for (i, &byte) in OV5640_AF_FIRMWARE.iter().enumerate() {
            bus.write_reg16(
                self.slv_addr,
                OV5640_AF_FW_BASE_ADDR.wrapping_add(i as u16),
                byte,
            )?;
        }
        bus.write_reg16(self.slv_addr, OV5640_CMD_MAIN, 0x00)?;
        bus.write_reg16(self.slv_addr, OV5640_CMD_ACK, 0x00)?;
        bus.write_reg16(self.slv_addr, OV5640_CMD_PARA0, 0x00)?;
        bus.write_reg16(self.slv_addr, OV5640_CMD_PARA1, 0x00)?;
        bus.write_reg16(self.slv_addr, OV5640_CMD_PARA2, 0x00)?;
        bus.write_reg16(self.slv_addr, OV5640_CMD_PARA3, 0x00)?;
        bus.write_reg16(self.slv_addr, OV5640_CMD_PARA4, 0x00)?;
        bus.write_reg16(self.slv_addr, OV5640_CMD_FW_STATUS, 0x7F)?;
        bus.write_reg16(self.slv_addr, 0x3000, 0x00)?;
        self.wait_fw_idle(bus, timeout_ms)
    }

    /// Starts single-shot or continuous autofocus (`ov5640_af_start`).
    pub fn start<B: SccbBus>(
        &self,
        bus: &mut B,
        continuous: bool,
        timeout_ms: u32,
    ) -> Result<(), CameraError> {
        bus.write_reg16(self.slv_addr, OV5640_CMD_MAIN, 0x01)?;
        bus.write_reg16(self.slv_addr, OV5640_CMD_MAIN, 0x08)?;
        self.wait_ack_clear(bus, timeout_ms)?;
        bus.write_reg16(self.slv_addr, OV5640_CMD_ACK, 0x01)?;
        let cmd = if continuous {
            OV5640_AF_CONTINUOUS
        } else {
            OV5640_AF_TRIG_SINGLE
        };
        bus.write_reg16(self.slv_addr, OV5640_CMD_MAIN, cmd)?;
        self.wait_ack_clear(bus, timeout_ms)
    }

    /// Sets autofocus mode (`0` = auto/continuous, `1` = manual; `ov5640_af_set_mode`).
    pub fn set_mode<B: SccbBus>(&self, bus: &mut B, mode: i32) -> Result<(), CameraError> {
        match mode {
            OV5640_AF_MODE_AUTO => self.start(bus, true, 2000),
            OV5640_AF_MODE_MANUAL => bus.write_reg16(self.slv_addr, OV5640_CMD_MAIN, 0x00),
            _ => Err(CameraError::InvalidArg),
        }
    }

    /// Triggers single-shot autofocus (`ov5640_af_trigger`).
    pub fn trigger<B: SccbBus>(&self, bus: &mut B) -> Result<(), CameraError> {
        self.start(bus, false, 2000)
    }

    /// Reads current autofocus status (`ov5640_af_get_status`).
    pub fn get_status<B: SccbBus>(&self, bus: &mut B) -> Result<Ov5640AfStatus, CameraError> {
        let raw = bus.read_reg16(self.slv_addr, OV5640_CMD_FW_STATUS)?;
        let focused = raw == OV5640_FW_STATUS_FOCUSED;
        let busy = !(raw == OV5640_FW_STATUS_IDLE || focused);
        Ok(Ov5640AfStatus { raw, focused, busy })
    }

    /// Manual lens position is not exposed in the OV5640 firmware driver (`ov5640_af_set_manual_position`).
    pub fn set_manual_position<B: SccbBus>(
        &self,
        _bus: &mut B,
        _position: u16,
    ) -> Result<(), CameraError> {
        Err(CameraError::NotSupported)
    }
}

