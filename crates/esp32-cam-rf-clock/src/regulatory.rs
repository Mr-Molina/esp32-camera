#[cfg(test)]
mod tests {
    use core::mem;

    use super::*;

    fn fnv1a_64(bytes: &[u8]) -> u64 {
        let mut hash = 0xcbf2_9ce4_8422_2325_u64;
        for &byte in bytes {
            hash ^= u64::from(byte);
            hash = hash.wrapping_mul(0x0100_0000_01b3);
        }
        hash
    }

    #[test]
    fn regdomain_table_matches_extracted_bytes() {
        assert_eq!(
            REGDOMAIN_TABLE.len(),
            552,
            "regdomain_table must be 552 bytes"
        );
        assert_eq!(
            &REGDOMAIN_TABLE[..4],
            &[0x30, 0x31, 0x00, 0x45],
            "regdomain_table header mismatch"
        );
        assert_eq!(
            &REGDOMAIN_TABLE[548..],
            &[0x0a, 0x23, 0x23, 0x14],
            "regdomain_table trailer mismatch"
        );
        assert_eq!(
            fnv1a_64(&REGDOMAIN_TABLE),
            0xe002_8cf5_183b_3722,
            "regdomain_table FNV-1a mismatch"
        );
    }

    #[test]
    fn regulatory_data_matches_layout_and_bytes() {
        assert_eq!(
            mem::size_of::<RegulatoryDataBlock>(),
            200,
            "RegulatoryDataBlock size must be 200"
        );
        assert!(
            mem::align_of::<RegulatoryDataBlock>() >= 2,
            "RegulatoryDataBlock align must be >= 2"
        );
        assert_eq!(
            REGULATORY_DATA.0.len(),
            200,
            "regulatory_data must be 200 bytes"
        );
        assert_eq!(
            &REGULATORY_DATA.0[..4],
            &[0x01, 0x00, 0x01, 0x0b],
            "regulatory_data header mismatch"
        );
        assert_eq!(
            &REGULATORY_DATA.0[196..],
            &[0x00, 0x00, 0x00, 0x00],
            "regulatory_data trailer mismatch"
        );
        assert_eq!(
            fnv1a_64(&REGULATORY_DATA.0),
            0x253d_dbba_57c0_4679,
            "regulatory_data FNV-1a mismatch"
        );
    }

    #[test]
    fn espnow_user_oui_matches_espressif_bytes() {
        assert_eq!(
            ESPNOW_USER_OUI_BYTES.len(),
            3,
            "g_espnow_user_oui must be 3 bytes"
        );
        assert_eq!(
            ESPNOW_USER_OUI_BYTES,
            [0x18, 0xfe, 0x34],
            "OUI bytes must match 18:FE:34"
        );
        assert_eq!(
            fnv1a_64(&ESPNOW_USER_OUI_BYTES),
            0xa827_5a18_e0ed_8e7d,
            "OUI FNV-1a mismatch"
        );
    }
}
